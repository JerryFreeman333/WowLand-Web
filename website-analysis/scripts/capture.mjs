import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
const require=createRequire(import.meta.url);
const { chromium }=require('/Applications/ChatGPT.app/Contents/Resources/cua_node/lib/node_modules/playwright/index.js');
const out=process.argv[2]||'website-analysis/screenshots';
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true, executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page=await browser.newPage({viewport:{width:1440,height:900}, colorScheme:'light'});
const resources=[]; const responses=[];
page.on('response',r=>responses.push({url:r.url(),status:r.status(),type:{}.toString.call(r.headers()['content-type'])}));
page.on('resource',r=>resources.push({url:r.url(),type:r._type || undefined}));
await page.goto('https://samsy.ninja/',{waitUntil:'domcontentloaded',timeout:120000});
await page.waitForTimeout(20000);
console.log('URL',page.url()); console.log('TITLE',await page.title()); console.log('TEXT\n'+await page.locator('body').innerText());
console.log('HTML\n'+await page.content());
console.log('STORAGE',JSON.stringify({local:await page.evaluate(()=>({...localStorage})),session:await page.evaluate(()=>({...sessionStorage})),cookies:await page.context().cookies()}));
console.log('RESOURCE_PERFORMANCE',JSON.stringify(await page.evaluate(()=>performance.getEntriesByType('resource').map(e=>({name:e.name,type:e.initiatorType,ms:Math.round(e.duration),bytes:e.transferSize}))),null,2));
await page.screenshot({path:out+'/desktop-home.png',fullPage:true});
await browser.close();
